-- ============================================================
-- Populate precinct race_ids from spatial intersection
-- ============================================================
-- Run this after loading UGRC precinct + political district shapefiles
-- and after populating district_races mappings. It derives which races
-- appear on each precinct's ballot via spatial intersection.
--
-- Usage: SELECT populate_precinct_races();
-- ============================================================

CREATE OR REPLACE FUNCTION populate_precinct_races()
RETURNS void AS $$
BEGIN
  UPDATE precincts p
  SET
    race_ids = sub.race_ids,
    district_info = sub.district_info
  FROM (
    SELECT
      p2.id AS precinct_id,
      jsonb_agg(DISTINCT dr.race_id) AS race_ids,
      jsonb_build_object(
        'congressional', max(CASE WHEN pd.district_type = 'us_congressional' THEN pd.district_name END),
        'state_senate',  max(CASE WHEN pd.district_type = 'state_senate'     THEN pd.district_name END),
        'state_house',   max(CASE WHEN pd.district_type = 'state_house'      THEN pd.district_name END),
        'county',        max(CASE WHEN pd.district_type = 'county'           THEN pd.district_name END)
      ) AS district_info
    FROM precincts p2
    JOIN political_districts pd ON ST_Intersects(p2.geom, pd.geom)
    JOIN district_races dr ON dr.district_id = pd.id
    GROUP BY p2.id
  ) sub
  WHERE p.id = sub.precinct_id;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- Helper functions for UGRC data loading (insert geometry via RPC)
-- ============================================================
-- Supabase JS client can't insert PostGIS geometry directly.
-- These functions accept GeoJSON strings and convert server-side.

CREATE OR REPLACE FUNCTION insert_precinct(
  p_precinct_code TEXT,
  p_county_id TEXT,
  p_geojson TEXT
) RETURNS void AS $$
BEGIN
  INSERT INTO precincts (precinct_code, county_id, geom)
  VALUES (
    p_precinct_code,
    p_county_id,
    ST_SetSRID(ST_GeomFromGeoJSON(p_geojson), 4326)
  );
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION insert_political_district(
  p_district_type TEXT,
  p_district_name TEXT,
  p_district_number TEXT,
  p_geojson TEXT
) RETURNS void AS $$
BEGIN
  INSERT INTO political_districts (district_type, district_name, district_number, geom)
  VALUES (
    p_district_type,
    p_district_name,
    p_district_number,
    ST_SetSRID(ST_GeomFromGeoJSON(p_geojson), 4326)
  );
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- Precinct lookup RPC (PostGIS spatial query)
-- ============================================================
-- Called by ballot-lookup/index.ts via supabase.rpc('lookup_precinct', ...)
-- Returns the precinct that contains the given point.

CREATE OR REPLACE FUNCTION lookup_precinct(p_lng float8, p_lat float8)
RETURNS SETOF precincts AS $$
  SELECT * FROM precincts
  WHERE ST_Contains(geom, ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326))
  LIMIT 1;
$$ LANGUAGE sql STABLE;


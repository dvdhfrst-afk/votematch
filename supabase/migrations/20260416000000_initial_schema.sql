-- User-own policies: users can read/write their own row via session_token header
-- The app passes session_token as a custom claim; here we use a helper that
-- reads current_setting('request.headers')::json->>'x-session-token'.
-- For service-role calls this is bypassed automatically.

-- NOTE: Function lives in `public` (not `auth`) — Supabase cloud reserves the
-- auth schema for its managed auth system and blocks custom functions there.
CREATE OR REPLACE FUNCTION public.session_token() RETURNS TEXT AS $$
  SELECT coalesce(
    current_setting('request.headers', true)::json->>'x-session-token',
    ''
  );
$$ LANGUAGE sql STABLE;

CREATE POLICY "Users own row select"
  ON users FOR SELECT
  USING (session_token = public.session_token());

CREATE POLICY "Users own row insert"
  ON users FOR INSERT
  WITH CHECK (session_token = public.session_token());

CREATE POLICY "Users own row update"
  ON users FOR UPDATE
  USING (session_token = public.session_token())
  WITH CHECK (session_token = public.session_token());

-- Matches: users can read/write their own matches

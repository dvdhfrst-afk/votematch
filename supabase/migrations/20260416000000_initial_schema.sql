CREATE TABLE sub_dimensions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  domain TEXT NOT NULL,
  name TEXT NOT NULL,
  spectrum_low TEXT NOT NULL,
  spectrum_high TEXT NOT NULL,
  display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE races (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  level TEXT NOT NULL CHECK (level IN ('federal', 'state', 'county')),
  district TEXT,
  election_date DATE NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('primary', 'general'))
);

CREATE TABLE candidates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  party TEXT,
  race_id UUID NOT NULL REFERENCES races(id) ON DELETE CASCADE,
  bio TEXT,
  photo_url TEXT,
  questionnaire_status TEXT NOT NULL DEFAULT 'not_invited'
    CHECK (questionnaire_status IN ('not_invited', 'invited', 'responded')),
  website_url TEXT,
  published BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE positions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  sub_dimension_id UUID NOT NULL REFERENCES sub_dimensions(id) ON DELETE CASCADE,
  score FLOAT NOT NULL CHECK (score >= 0 AND score <= 1),
  confidence TEXT NOT NULL CHECK (confidence IN ('high', 'medium', 'low')),
  source_citations JSONB,
  nuance_notes TEXT,
  ai_summary TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE questionnaire_responses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  race_id UUID NOT NULL REFERENCES races(id) ON DELETE CASCADE,
  response_data JSONB NOT NULL,
  attestation TEXT NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ
);

CREATE TABLE candidate_sources (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  source_type TEXT NOT NULL CHECK (source_type IN (
    'campaign_website', 'extracted_positions', 'voting_record',
    'fec_financials', 'news_article', 'questionnaire'
  )),
  raw_data TEXT NOT NULL,
  url TEXT,
  title TEXT,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE candidate_contacts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(candidate_id)
);

-- Political district layers (loaded from UGRC SGID, used to derive precinct → race mapping)
CREATE TABLE political_districts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_type TEXT NOT NULL CHECK (district_type IN (
    'us_congressional', 'state_senate', 'state_house', 'county', 'school_board', 'municipal'
  )),
  district_name TEXT NOT NULL,
  district_number TEXT,
  geom GEOMETRY(MultiPolygon, 4326),
  source TEXT NOT NULL DEFAULT 'ugrc_sgid',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Maps districts to the races that occur within them for a given election
CREATE TABLE district_races (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  district_id UUID NOT NULL REFERENCES political_districts(id) ON DELETE CASCADE,
  race_id UUID NOT NULL REFERENCES races(id) ON DELETE CASCADE,
  UNIQUE(district_id, race_id)
);

CREATE TABLE precincts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  precinct_code TEXT, -- UGRC PrecinctID field
  county_id TEXT,     -- UGRC CountyID field
  geom GEOMETRY(MultiPolygon, 4326),
  -- race_ids is derived via spatial intersection with political_districts + district_races.
  -- Cached here for fast lookup; regenerated by populate_precinct_races().
  race_ids JSONB,
  district_info JSONB
);

CREATE TABLE users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_token TEXT UNIQUE NOT NULL,
  address_text TEXT,
  precinct_id UUID REFERENCES precincts(id) ON DELETE SET NULL,
  quick_match_answers JSONB,
  weights JSONB,
  email TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE matches (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  race_id UUID NOT NULL REFERENCES races(id) ON DELETE CASCADE,
  score FLOAT NOT NULL,
  explanation JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE corrections (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_id UUID NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  position_id UUID NOT NULL REFERENCES positions(id) ON DELETE CASCADE,
  submitted_by TEXT NOT NULL,
  evidence TEXT,
  status TEXT NOT NULL DEFAULT 'submitted'
    CHECK (status IN ('submitted', 'accepted', 'rejected')),
  resolution_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ
);

CREATE TABLE email_optins (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT NOT NULL UNIQUE,
  precinct_id UUID REFERENCES precincts(id) ON DELETE SET NULL,
  opted_in_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE feedback_responses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(id) ON DELETE SET NULL,
  did_vote BOOLEAN,
  changed_vote TEXT CHECK (changed_vote IN ('yes', 'no', 'not_sure')),
  races_changed INT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


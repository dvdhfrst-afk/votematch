-- Office-scope schema (council-approved 2026-05-26).
--
-- Adds the structured measurement primitives the matcher needs to weight
-- candidate answers against the actual authority of the office a candidate
-- is running for. See the council decision in conversation notes for the
-- full rationale.
--
-- Design constraints:
--   - Vocabulary is versioned from day one ("_v1" suffix on the array col)
--     so a future taxonomy revision is a new column + dual-write, not a
--     destructive migration.
--   - Bodies inherit defaults from chamber_type. Per-body overrides require
--     a primary-source citation (enforced in write.ts). 95% of bodies will
--     never need an override.
--   - voter_facing_scope.one_liner is agent-prose with a strict length cap
--     and a required statute_url / charter_url. can_do / cannot_do are
--     templated at read-time from authority_statement; not stored per body.

-- ── ENUMS ──────────────────────────────────────────────────────────────

CREATE TYPE policy_authority_domain_t AS ENUM (
  'land_use_housing',
  'transportation_infrastructure',
  'public_safety',
  'justice',
  'utilities',
  'education',
  'health_environment',
  'parks_culture',
  'fiscal',
  'economic_regulation',
  'elections_governance',
  'social_services'
);

CREATE TYPE authority_mode_t AS ENUM (
  'legislative',
  'executive',
  'quasi_judicial',
  'advisory',
  'confirming'
);

CREATE TYPE jurisdiction_level_t AS ENUM (
  'federal',
  'state',
  'county',
  'municipal',
  'sub_municipal',
  'special_district',
  'judicial'
);

-- ── TABLES ─────────────────────────────────────────────────────────────

-- chamber_type_defaults: the "95% case" lookup. Each chamber_type ships
-- with the default authority profile. Bodies get this on first write
-- unless the agent provides a citation-backed override.
CREATE TABLE chamber_type_defaults (
  chamber_type           text PRIMARY KEY,
  jurisdiction_level     jurisdiction_level_t NOT NULL,
  default_domains_v1     policy_authority_domain_t[] NOT NULL,
  default_authority_mode authority_mode_t NOT NULL,
  requires_voter_scope_copy boolean NOT NULL DEFAULT false,
  notes                  text,
  updated_at             timestamptz NOT NULL DEFAULT now()
);

-- authority_statement: the lookup the renderer uses to produce can_do /
-- cannot_do bullets from a body's (domain, mode, level) tuple. Reviewed by
-- humans, NOT generated by the agent. Updating one row updates every body
-- that draws from it.
CREATE TABLE authority_statement (
  id                  serial PRIMARY KEY,
  domain              policy_authority_domain_t NOT NULL,
  authority_mode     authority_mode_t NOT NULL,
  jurisdiction_level jurisdiction_level_t NOT NULL,
  can_do_text         text NOT NULL,
  cannot_do_text      text,
  statute_template    text,
  vocabulary_version  text NOT NULL DEFAULT 'v1',
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (domain, authority_mode, jurisdiction_level, vocabulary_version)
);

CREATE INDEX idx_authority_statement_lookup
  ON authority_statement (jurisdiction_level, domain, authority_mode);

-- ── BODY / OFFICE COLUMNS ──────────────────────────────────────────────

ALTER TABLE governing_bodies
  ADD COLUMN policy_authority_domains_v1 policy_authority_domain_t[],
  ADD COLUMN authority_mode authority_mode_t,
  ADD COLUMN domain_overrides jsonb,
  ADD COLUMN voter_facing_scope jsonb,
  ADD COLUMN statute_url text,
  ADD COLUMN charter_url text;

ALTER TABLE offices
  ADD COLUMN policy_authority_domains_v1 policy_authority_domain_t[],
  ADD COLUMN authority_mode authority_mode_t,
  ADD COLUMN domain_overrides jsonb,
  ADD COLUMN voter_facing_scope jsonb,
  ADD COLUMN statute_url text,
  ADD COLUMN charter_url text;

CREATE INDEX idx_governing_bodies_domains_gin
  ON governing_bodies USING gin (policy_authority_domains_v1);

CREATE INDEX idx_offices_domains_gin
  ON offices USING gin (policy_authority_domains_v1);

COMMENT ON COLUMN governing_bodies.policy_authority_domains_v1 IS
  'Authority domains from the v1 vocabulary. Inherits chamber_type_defaults.default_domains_v1 unless domain_overrides supplies a citation-backed deviation.';
COMMENT ON COLUMN governing_bodies.domain_overrides IS
  '{ added: domain[], removed: domain[], citations: [{ url, kind, snippet }], reviewed_by: text|null }';
COMMENT ON COLUMN governing_bodies.voter_facing_scope IS
  '{ one_liner: <=160-char prose, statute_url, charter_url, locale: "en", citation_ref: <citation index> }';
